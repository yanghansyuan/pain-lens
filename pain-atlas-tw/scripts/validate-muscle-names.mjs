import assert from 'node:assert/strict';
import fs from 'node:fs';
import {localMuscleName} from '../app/muscle-names.ts';
const atlas=JSON.parse(fs.readFileSync(new URL('../public/models/atlas.json',import.meta.url),'utf8'));
const muscles=atlas.parts.filter(p=>p.system==='muscular');
const parts=new Map(atlas.parts.map(p=>[p.id,p]));
const concepts=atlas.concepts.filter(c=>c.elements.length&&c.elements.every(id=>parts.get(id)?.system==='muscular'));
const missing=muscles.filter(p=>!localMuscleName(p.name));
assert.deepEqual(missing.map(p=>p.name),[],'Muscle names missing Traditional Chinese translations');
for(const muscle of muscles)assert.doesNotMatch(localMuscleName(muscle.name),/[a-z]/i);
assert.deepEqual(concepts.filter(c=>!localMuscleName(c.name)).map(c=>c.name),[],'Muscle concepts missing Traditional Chinese translations');
for(const concept of concepts)assert.doesNotMatch(localMuscleName(concept.name),/[a-z]/i);
assert.equal(localMuscleName('Right gemellus inferior'),'右側下孖肌');
assert.equal(localMuscleName('Left gemellus superior'),'左側上孖肌');
assert.equal(localMuscleName('Long head of right biceps femoris'),'右側股二頭肌（長頭）');
assert.equal(localMuscleName('Abductor digiti minimi of right foot'),'右側小趾外展肌');
assert.equal(localMuscleName('Abductor digiti minimi of right hand'),'右側小指外展肌');
assert.equal(localMuscleName('Anterior papillary muscle of right ventricle'),'右心室前乳突肌');
assert.equal(localMuscleName('Right inferior rectus'),'右側下直肌');
assert.equal(localMuscleName('Right rectus femoris'),'右側股直肌');
assert.equal(localMuscleName('Nerve to right gemellus inferior'),undefined);
assert.equal(localMuscleName('Right femur'),undefined);
console.log(`Verified complete Traditional Chinese labels for all ${muscles.length} muscle meshes and ${concepts.length} muscle-only concepts, with laterality, heads, parts, hand/foot distinctions, and safe fallback for other anatomy.`);
